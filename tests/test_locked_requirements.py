import operator
from pathlib import Path
import re
import unittest

ROOT = Path(__file__).resolve().parents[1]
SOURCE, LOCK = ROOT / "requirements-dev.in", ROOT / "requirements-dev.txt"
WORKFLOWS = [ROOT / ".github/workflows/catalog.yml", ROOT / ".github/workflows/scan.yml", ROOT / "automation/publish.yml"]
NAME = re.compile(r"^([A-Za-z0-9][A-Za-z0-9._-]*)")
OPERATORS = {">=": operator.ge, "<=": operator.le, "==": operator.eq, "!=": operator.ne, "<": operator.lt, ">": operator.gt}


def version(text):
    """Release segment as a comparable tuple without trailing zeros, enough for the plain numeric bounds used here."""
    parts = [int(part) for part in re.match(r"\d+(?:\.\d+)*", text).group(0).split(".")]
    while len(parts) > 1 and parts[-1] == 0:
        parts.pop()
    return tuple(parts)


def normalized(name):
    return re.sub(r"[-_.]+", "-", name).lower()


def requirements(path):
    """Map each requirement in a pip requirements file to its specifier and hashes, joining backslash continuations."""
    found = {}
    for line in re.sub(r"\\\n", " ", path.read_text()).splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            name = NAME.match(line).group(1)
            spec = line[len(name):].split("--hash", 1)[0].strip()
            found[normalized(name)] = (re.sub(r"^\[[^]]*\]", "", spec), re.findall(r"--hash=sha256:([0-9a-f]{64})", line))
    return found


class LockedRequirementTests(unittest.TestCase):
    def test_lock_is_pip_compile_output_with_hashes_from_the_source_file(self):
        # Dependabot recognises a pip-compile lock by its header and a same-named .in file, and reruns the recorded command.
        text = LOCK.read_text()
        self.assertTrue(text.startswith("#\n# This file is autogenerated by pip-compile with Python 3.12\n"))
        self.assertRegex(text, r"(?m)^#    pip-compile --generate-hashes --strip-extras requirements-dev\.in$")

    def test_every_locked_package_is_pinned_and_hashed(self):
        locked = requirements(LOCK)
        self.assertIn("jsonschema", locked)
        for name, (spec, hashes) in locked.items():
            with self.subTest(package=name):
                self.assertRegex(spec, r"^==[0-9][\w.+!-]*$")
                self.assertTrue(hashes)

    def test_every_direct_requirement_is_locked(self):
        source, locked = requirements(SOURCE), requirements(LOCK)
        self.assertTrue(source)
        for name, (spec, hashes) in source.items():
            with self.subTest(package=name):
                self.assertIn(name, locked)
                self.assertEqual(hashes, [])
                pinned = version(locked[name][0][2:])
                for comparison, bound in re.findall(r"(>=|<=|==|!=|<|>)\s*([^,\s]+)", spec):
                    self.assertTrue(OPERATORS[comparison](pinned, version(bound)), f"{name} {locked[name][0]} is outside {spec}")

    def test_workflows_install_only_from_the_hashed_lock(self):
        installs = []
        for path in WORKFLOWS:
            text = path.read_text()
            installs += [(path.name, line.strip()) for line in text.splitlines() if "pip install" in line]
            for line in text.splitlines():
                if "cache-dependency-path:" in line:
                    with self.subTest(workflow=path.name, line=line.strip()):
                        self.assertTrue(line.rstrip().endswith("requirements-dev.txt"))
        self.assertEqual([name for name, _ in installs], ["catalog.yml", "scan.yml", "publish.yml"])
        for name, line in installs:
            with self.subTest(workflow=name):
                self.assertRegex(line, r"^- run: python -m pip install --require-hashes -r (\.pipeline/source/)?requirements-dev\.txt$")

    def test_regeneration_is_documented_with_the_lock_command(self):
        command = re.search(r"^#    (pip-compile .+)$", LOCK.read_text(), re.M).group(1)
        self.assertIn(command, (ROOT / "docs/maintenance.md").read_text())


if __name__ == "__main__":
    unittest.main()
